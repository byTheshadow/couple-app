/** 同一条路、同一天、同一块 → 同一道题；每天换一批 */
export function dayNo() {
  return Math.floor((Date.now() + 8 * 3600 * 1000) / 86400000)
}

export function questionAt(seed, platform, day) {
  const d = day == null ? dayNo() : day
  const n = BANK.length
  const idx = ((seed * 31 + platform * 7 + d * 17) % n + n) % n
  const item = BANK[idx]
  const opts = item.o.slice()
  const rng = mulberry32((seed ^ Math.imul(platform + 1, 0x9e3779b1) ^ Math.imul(d + 1, 0x85ebca6b)) >>> 0)
  for (let i = opts.length - 1; i > 0; i--) {
    const j = (rng() * (i + 1)) | 0
    const tmp = opts[i]
    opts[i] = opts[j]
    opts[j] = tmp
  }
  return { key: seed + ':' + platform + ':' + d, q: item.q, opts, right: item.o[0] }
}

/** 礼物方块：随机一句，不要求稳定（两个人各自看到自己的那一句） */
export function giftAt() {
  return GIFTS[(Math.random() * GIFTS.length) | 0]
}