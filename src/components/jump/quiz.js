/** 同一条路、同一块 → 同一道题；选项顺序也固定 */
export function questionAt(seed, platform) {
  const n = BANK.length
  const idx = ((seed * 31 + platform * 7) % n + n) % n
  const item = BANK[idx]
  const opts = item.o.slice()
  const rng = mulberry32((seed ^ Math.imul(platform + 1, 0x9e3779b1)) >>> 0)
  for (let i = opts.length - 1; i > 0; i--) {
    const j = (rng() * (i + 1)) | 0
    const tmp = opts[i]
    opts[i] = opts[j]
    opts[j] = tmp
  }
  return { key: seed + ':' + platform, q: item.q, opts, right: item.o[0] }
}

/** 礼物方块：随机一句，不要求稳定（两个人各自看到自己的那一句） */
export function giftAt() {
  return GIFTS[(Math.random() * GIFTS.length) | 0]
}