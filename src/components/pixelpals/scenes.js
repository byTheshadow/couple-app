/** 把已经收到的礼物摆进房间 */
export function drawGifts(ctx, owned, t) {
  for (const g of GIFTS) {
    if (!owned.includes(g.k)) continue
    const s = SPRITE_LIB[g.spr]
    if (!s) continue
    pat(ctx, s.rows, s.map, g.at[0], g.at[1])
    if (g.flick && Math.floor(t * 6) % 2) R(ctx, g.flick[2], g.at[0] + g.flick[0], g.at[1] + g.flick[1], 1, 1)
  }
}

/** 睡觉关灯以后，有光的礼物（台灯、蜡烛）还亮着 */
export function drawGiftGlows(ctx, owned) {
  for (const g of GIFTS) {
    if (!g.glow || !owned.includes(g.k)) continue
    const [x, y, r, a] = g.glow
    const gr = ctx.createRadialGradient(x, y, 2, x, y, r)
    gr.addColorStop(0, `rgba(255,214,130,${a / 100})`)
    gr.addColorStop(1, 'rgba(255,214,130,0)')
    ctx.fillStyle = gr
    ctx.fillRect(0, 0, W, H)
  }
}

